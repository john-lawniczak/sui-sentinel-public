#!/bin/sh
set -eu
# Files contain complete URL-encoded DSNs/tokens. Never echo their contents.
if [ -n "${DIAGNOSIS_DATABASE_URL_FILE:-}" ]; then
  DIAGNOSIS_DATABASE_URL=$(cat "$DIAGNOSIS_DATABASE_URL_FILE"); export DIAGNOSIS_DATABASE_URL
fi
if [ -n "${SENTINEL_DELIVERY_DATABASE_URL_FILE:-}" ]; then
  SENTINEL_DELIVERY_DATABASE_URL=$(cat "$SENTINEL_DELIVERY_DATABASE_URL_FILE"); export SENTINEL_DELIVERY_DATABASE_URL
fi
if [ -n "${SENTINEL_WEBHOOK_TOKEN_FILE:-}" ]; then
  SENTINEL_WEBHOOK_TOKEN=$(cat "$SENTINEL_WEBHOOK_TOKEN_FILE"); export SENTINEL_WEBHOOK_TOKEN
fi
if [ -n "${SUI_API_KEY_FILE:-}" ]; then
  SUI_API_KEY=$(cat "$SUI_API_KEY_FILE"); export SUI_API_KEY
fi
if [ -n "${SENTINEL_WEBHOOK_URL_FILE:-}" ]; then
  SENTINEL_WEBHOOK_URL=$(cat "$SENTINEL_WEBHOOK_URL_FILE"); export SENTINEL_WEBHOOK_URL
fi
if [ -n "${SENTINEL_QUERY_DATABASE_URL_FILE:-}" ]; then
  SENTINEL_QUERY_DATABASE_URL=$(cat "$SENTINEL_QUERY_DATABASE_URL_FILE"); export SENTINEL_QUERY_DATABASE_URL
fi
if [ -n "${SENTINEL_MCP_TOKEN_FILE:-}" ]; then
  SENTINEL_MCP_TOKEN=$(cat "$SENTINEL_MCP_TOKEN_FILE"); export SENTINEL_MCP_TOKEN
fi
exec sui-sentinel "$@"
